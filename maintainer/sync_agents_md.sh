#!/bin/sh
# Copy CLAUDE.md (master) to AGENTS.md (same text for other AI agents).
#   sh maintainer/sync_agents_md.sh
set -eu
cd "$(dirname "$0")/.."
sed -e 's/^# CLAUDE.md$/# AGENTS.md/' \
    -e 's#^This file gives instructions to Claude Code (claude.ai/code) for work in this folder.#This file gives instructions to AI coding agents for work in this folder.#' \
    -e 's#^> `AGENTS.md` is the same text for other agents. When you change this file, copy it to `AGENTS.md`#> `CLAUDE.md` is the master copy of this text. Do not edit this file. Edit `CLAUDE.md`, then copy it here#' \
    CLAUDE.md > AGENTS.md
